/**
 * Baku City Circuit, traced from the real street circuit.
 *
 * Same method as Spa, and the same reasoning applies: a circuit's shape is an input.
 * Choosing turn angles that sum to a whole number of turns only guarantees the loop
 * closes, and filtering generated angle sets for ones that do not cross themselves
 * keeps CONVEX REGULAR shapes — which is why the previous Baku was a heptagon.
 *
 * The coordinates come from the circuit path of the Wikimedia Commons 2023 course
 * layout diagram (File:2023 F1 CourseLayout Azerbaijan.svg), sampled along the real
 * Bezier curves.
 *
 * CHOOSING THE SOURCE MATTERED, and this is the part worth recording. The first
 * diagram tried (File:Baku Formula One circuit map.svg) contains a 95 m section that
 * is traced TWICE, in opposite directions, so its centreline comes within 0.6 m of
 * itself. That is not a tight corner, it is a defect: the surfaces of a real road
 * cannot occupy the same ground. It was not obvious from the picture, which looks
 * correct, and it was found only by measuring the centreline's closest self-approach
 * and finding a hairpin whose legs were a metre apart.
 *
 * The 2023 diagram measures 22.6 m at its closest self-approach, which is a plausible
 * street-circuit squeeze, and it builds to a valid circuit at a normal 9 m half
 * width where the other needed 6 m to avoid overlapping itself.
 *
 * MEASURED: 6007 m against the real circuit's 6003, 419 control points, zero
 * self-crossings. Corners span roughly 60-195 km/h, and it has the character the
 * real one does: a very long main straight along the seafront, a tight and technical
 * middle sector, and a slow final complex.
 *
 * TWO PROCESS NOTES, because both cost time:
 *
 *  - The trace is sampled ALONG the curves at even arc length, not by taking every
 *    Nth point of a raster. Decimating a raster loses the curve, and the spline
 *    through the survivors overshoots badly enough to invent corners.
 *
 *  - One pass of light smoothing is applied, because a resampled curve leaves
 *    sub-metre jitter that the spline amplifies. Without it, coarse control spacing
 *    invents corners and self-crossings; with it, the same spacing gives a valid
 *    circuit. Smoothing removes sampling noise, it does not reshape the layout.
 *
 * Elevation is not represented: the engine is two-dimensional.
 */
